#!/usr/bin/env python3
"""Bake anti-aliased glyphs from a TTF into src/font_data.h (8-bit alpha).

Usage: python3 tools/gen_font.py [path/to/font.ttf]
Default font: Liberation Sans Bold (SIL Open Font License).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
CHARS = " -.0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
SIZES = {"font_label": 27, "font_tape": 23, "font_msg": 21}
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "font_data.h")


def bake(name, px):
    font = ImageFont.truetype(FONT, px)
    ascent, descent = font.getmetrics()
    bitmap, glyphs = [], []
    for ch in CHARS:
        adv = round(font.getlength(ch))
        box = font.getbbox(ch)  # relative to the ascender line
        w, h = box[2] - box[0], box[3] - box[1]
        if ch == " " or w <= 0 or h <= 0:
            glyphs.append((len(bitmap), 0, 0, 0, 0, adv))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
        glyphs.append((len(bitmap), w, h, box[0], box[1] - ascent, adv))
        bitmap.extend(img.getdata())
    # cap height of digits, used for vertical centering
    cap = -min(g[4] for g, c in zip(glyphs, CHARS) if c.isdigit())
    lines = [f"static const uint8_t {name}_bitmap[] = {{"]
    for i in range(0, len(bitmap), 24):
        lines.append("  " + ",".join(str(b) for b in bitmap[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const FontGlyph {name}_glyphs[] = {{")
    for c, g in zip(CHARS, glyphs):
        lines.append(f"  {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}}, // '{c}'")
    lines.append("};")
    lines.append(f'static const Font {name} = {{{name}_bitmap, {name}_glyphs, "{CHARS}", {cap}}};')
    return "\n".join(lines)


def main():
    parts = [
        "// Generated by tools/gen_font.py from " + os.path.basename(FONT) + " -- do not edit.",
        "#pragma once",
        '#include "canvas.h"',
        "",
    ]
    for name, px in SIZES.items():
        parts.append(bake(name, px))
        parts.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(parts))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
